package permission

import "testing"

// SharedGitChange: git that would change what a work tree shares with its
// checkout (branches and other refs by name, git settings, the list of
// work trees) is named; git that keeps to the work tree's own branch, or
// only reads, is not.
func TestSharedGitChange(t *testing.T) {
	e := mustEngine(t, testOptions(ModeDefault, rules{}))
	for _, cmd := range []string{
		"git update-ref refs/heads/main HEAD",
		"git update-ref -d refs/heads/x",
		"/usr/bin/git update-ref refs/heads/main HEAD",
		"git-update-ref refs/heads/main HEAD",
		"sudo git update-ref refs/heads/main HEAD",
		"ls && git branch -D x",
		"echo x | xargs git branch -D",
		"sh -c 'git update-ref refs/heads/main HEAD'",
		"git symbolic-ref HEAD refs/heads/main",
		"git symbolic-ref -d HEAD",
		"git branch -f main HEAD",
		"git branch -D old",
		"git branch -vD old",
		"git branch -m main trunk",
		"git branch --delete old",
		"git branch --mov main trunk",
		"git checkout -B main",
		"git checkout -qB main origin/main",
		"git checkout --ignore-other-worktrees main",
		"git switch -C main",
		"git switch --force-create main",
		"git switch --ignore-other-worktrees main",
		"git worktree remove ../x",
		"git worktree prune",
		"git worktree add -B main ../x",
		"git worktree add --force ../x main",
		"git push . HEAD:main",
		"git push /repo HEAD:main",
		"git push ../repo HEAD:main",
		"git push --repo=. HEAD:main",
		"git push $TO HEAD:main",
		"git fetch origin main:main",
		"git fetch . HEAD:refs/heads/main",
		"git pull origin +main:main",
		"git fetch origin $SPEC",
		"git rebase --update-refs main",
		"git config core.fsmonitor x",
		"git config --local core.hooksPath /tmp/h",
		"git config --unset core.x",
		"git config set core.x y",
		"git config -e",
		`git config user.email "$E"`,
		"git config -f /repo/.git/config core.hooksPath x",
		"git remote set-url origin x",
		"git remote add up https://example.com/x.git",
		"git replace a b",
		"git replace -d a",
		"git stash clear",
		"git tag -d v1",
		"git tag -f v1",
		"git reflog expire --expire=now --all",
		"git filter-branch --all",
		"git -c alias.x=update-ref x refs/heads/main HEAD",
		"git -c 'alias.x=!sh' x",
		"GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=alias.x GIT_CONFIG_VALUE_0=update-ref git x refs/heads/main HEAD",
		"git $SUB refs/heads/main HEAD",
	} {
		if got := e.SharedGitChange(cmd); got == "" {
			t.Errorf("SharedGitChange(%q) = nothing, want what it changes", cmd)
		}
	}
	for _, cmd := range []string{
		"git status",
		"git log --oneline",
		"git diff HEAD",
		"git commit -am x",
		"git reset --hard HEAD~1",
		"git branch",
		"git branch -a",
		"git branch -vv",
		"git branch new-thing",
		"git branch --sort -committerdate",
		"git branch --format '%(refname)'",
		"git branch -u origin/main",
		"git branch --show-current",
		"git branch --color",
		"git checkout -b new",
		"git checkout main.go",
		"git checkout -- a.go",
		"git checkout -f",
		"git switch -c new",
		"git switch main",
		"git switch --force main",
		"git worktree list",
		"git worktree add -b new ../x",
		"git push origin HEAD",
		"git push -u origin feature",
		"git push --force origin x",
		"git push origin $BR",
		"git fetch origin",
		"git fetch --all",
		"git fetch origin main",
		"git fetch origin +refs/heads/*:refs/remotes/origin/*",
		"git fetch --depth 1 git@github.com:x/y.git main",
		"git pull --rebase origin main",
		"git rebase -i HEAD~3",
		"git rebase --onto a b",
		"git config user.name",
		"git config --get core.x",
		"git config -l",
		"git config --global user.name x",
		"git config get core.x",
		"git config --list --show-origin",
		"git remote -v",
		"git remote show origin",
		"git remote get-url origin",
		"git replace",
		"git replace -l",
		"git replace --format=medium",
		"git stash",
		"git stash pop",
		"git stash list",
		"git tag v1",
		"git tag -a v1 -m 'release d'",
		"git tag -l",
		"git tag --format='%(refname)'",
		"git reflog",
		"git reflog show main",
		"git -c core.pager=cat log",
		"git help update-ref",
		"echo update-ref",
		"git gc",
		"$G update-ref refs/heads/main HEAD", // a name only known when it runs: GitPlaces's to refuse
	} {
		if got := e.SharedGitChange(cmd); got != "" {
			t.Errorf("SharedGitChange(%q) = %q, want nothing", cmd, got)
		}
	}
}
