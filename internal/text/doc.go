// Package text is everything gnosh knows about text in a terminal that can be
// worked out from the text alone: where one character ends and the next
// begins, how many cells a string takes, how to cut it and wrap it, and how
// to colour it. Nothing here reads the terminal, the clock or the
// environment, and the package keeps no state: every function gives the same
// answer for the same arguments.
//
// gnosh draws its own interface, so the rest of it leans on this package to
// know exactly where the cursor ends up after a string is printed.
//
// # Characters and cells
//
// A terminal is a grid of cells. What a reader takes for one character may
// be several code points (a letter and its accents, an emoji with a skin
// tone, a flag), and may take one cell, two, or none. Graphemes and
// NextGrapheme split text into those characters, which Unicode calls
// extended grapheme clusters, by the rules of UAX #29. Width counts the
// cells a string takes; its documentation lists the rules. ExpandTabs turns
// tabs into spaces, which Width cannot do because a tab's size depends on
// where it stands.
//
// The characters Unicode calls ambiguous in width are one cell wide unless a
// caller says otherwise with a Metrics value, whose methods mirror the
// package's functions.
//
// # Escape sequences
//
// Colours, styles and hyperlinks reach a terminal as escape sequences mixed
// into the text. NextToken and Tokens split a string into plain text and
// sequences; Strip removes the sequences; VisibleWidth counts cells without
// them. Truncate, PadRight, PadLeft, Center and Wrap all measure this way,
// so styled strings can be laid out like plain ones.
//
// Truncate cuts a string to a width and Wrap breaks it into lines, both on
// character boundaries and both without ever splitting a wide character. A
// colour or hyperlink that is open where Wrap ends a line is closed there
// and opened again on the next line, so each line can be printed on its own.
//
// An escape sequence that was cut short, by the end of the string or by a
// byte that cannot be part of it, would take in whatever is printed next.
// The functions that lay text out (Truncate, the padding functions,
// ExpandTabs and Wrap) remove such sequences; Token.Complete tells them
// apart for callers that read a stream in pieces.
//
// # Colour
//
// A Style is a foreground, a background and a few attributes; its Render
// method wraps text in the sequences that show it. A Profile says how much
// colour the output can take (none, 16 colours, 256, or 24-bit) and
// DetectProfile works one out from the environment variables it is handed.
// A style set to a lesser profile writes the nearest colour that profile
// has, and under NoColor it writes the text alone. Hyperlink makes a
// clickable link. Gradient colours a string from one colour to another
// along its width, character by character.
//
// # The tables
//
// The Unicode properties behind all this are in tables.go, generated by the
// program in the gen directory from the Unicode Character Database for one
// pinned Unicode version, the one the Go standard library's unicode package
// uses. The file names its sources and their checksums. The official test
// files under testdata check the result. Regenerating is done by hand:
//
//	go run ./internal/text/gen -fetch > tables.go
//
// # Cost
//
// Every function takes time proportional to the length of its input. Width,
// VisibleWidth, NextGrapheme, NextToken and the iterators do not allocate.
// The others allocate their result, and return their argument itself when
// there is nothing to change.
