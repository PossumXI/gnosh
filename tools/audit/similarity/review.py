def main():
    lines = list(csv.DictReader(open(os.path.join(X.WORK, 'lines.tsv'), encoding='utf-8', errors='replace'), delimiter='\t', quoting=csv.QUOTE_NONE))
    tok = list(csv.DictReader(open(os.path.join(X.WORK, 'tok.tsv'), encoding='utf-8', errors='replace'), delimiter='\t', quoting=csv.QUOTE_NONE))
    items = collections.OrderedDict()  # (path, measure, corpus) -> dict

    def text_of(path, rng):
        src = X.read_text(os.path.join(X.NEW_TREE, path)) or []
        if not rng or '-' not in rng:
            return src
        a, b = (int(x) for x in rng.split('-'))
        return src[a - 1:b]

    def add(path, measure, corp, value, rng, source, src_rng):
        key = (path, measure, corp)
        if key not in items:
            items[key] = dict(path=path, measure=measure, corpus=corp, value=value, lines=rng, source=source, source_lines=src_rng,
                              sort=classify(text_of(path, rng)) if rng else '')

    pre = {'core': 'crush', 'ext': 'hist', 'libs': 'libs'}
    for corp in ('core', 'ext', 'libs'):
        cc = 'core' if corp == 'ext' else corp
        ln = [r for r in lines if r['set'] == 'new-tree' and r['group'] == 'new' and r['kind'] in ('code', 'prompt') and r['corpus'] == corp]
        for r in sorted([r for r in ln if int(r['sigd']) >= 10], key=lambda r: -float(r['share']))[:20]:
            if float(r['share']) > 0:
                add(r['path'], 'line share', pre[corp], '%s%% (%s of %s lines)' % (r['share'], r['sigd_match'], r['sigd']), '', r['best_src'], '')
        for r in sorted(ln, key=lambda r: -int(r['rawrun']))[:20]:
            if int(r['rawrun']) > 0:
                add(r['path'], 'line run', pre[corp], '%s lines' % r['rawrun'], '', r['top'], '')
        for r in sorted(ln, key=lambda r: -int(r['lrun']))[:20]:
            if int(r['lrun']) >= 6:
                add(r['path'], 'lines each somewhere in the corpus', pre[corp], '%s lines' % r['lrun'], '', '', '')
        for form, lab in (('exact', 'exact tokens'), ('abstract', 'abstract tokens')):
            tn = [r for r in tok if r['set'] == 'new-tree' and r['group'] == 'new' and r['corpus'] == corp and r['form'] == form]
            tc = [r for r in tok if r['set'].startswith('ctl:') and r['corpus'] == cc and r['form'] == form and int(r['ntok']) >= 100]
            for r in sorted(tn, key=lambda r: (-int(r['vrun']), -int(r['vcov'])))[:20]:
                if int(r['vrun']) > 0:
                    add(r['path'], lab + ', varied run', pre[corp], '%s tokens' % r['vrun'], r['vrun_target_lines'], r['vrun_source'], r['vrun_source_lines'])
            for r in sorted(tn, key=lambda r: -int(r['single']))[:20]:
                if int(r['single']) > 0:
                    add(r['path'], lab + ', run with lists and tables', pre[corp], '%s tokens, %s distinct windows' % (r['single'], r['single_dw']), r['target_lines'], r['source'], r['source_lines'])
            for key, lab2, show in ((lambda r: 100.0 * int(r['vcov']) / max(1, int(r['ntok'])), ', varied cover', lambda v: '%.1f%%' % v),
                                    (lambda r: 100.0 * int(r['cov']) / max(1, int(r['ntok'])), ', cover with lists and tables', lambda v: '%.1f%%' % v)):
                big = [r for r in tn if int(r['ntok']) >= 100]
                cmax = max((key(r) for r in tc), default=0)
                for r in sorted(big, key=lambda r: -key(r))[:20]:
                    if key(r) > 0 and (key(r) > cmax or lab2 == ', varied cover'):
                        add(r['path'], lab + lab2, pre[corp], show(key(r)), r['vrun_target_lines'] if 'varied' in lab2 else r['target_lines'],
                            r['vrun_source'] if 'varied' in lab2 else r['source'], r['vrun_source_lines'] if 'varied' in lab2 else r['source_lines'])
    cols = ['path', 'measure', 'corpus', 'value', 'lines', 'source', 'source_lines', 'sort', 'verdict']
    with open(os.path.join(X.WORK, 'review.tsv'), 'w') as f:
        f.write('\t'.join(cols) + '\n')
        for it in items.values():
            it['verdict'] = VERDICTS.get(it['path'], '')
            f.write('\t'.join(str(it[c]) for c in cols) + '\n')
    # one line per file
    by = collections.OrderedDict()
    for it in items.values():
        by.setdefault(it['path'], []).append(it)
    out = ['| file | where it stands highest | what the matched lines are | judgement |', '|---|---|---|---|']
    sorts = collections.Counter()
    for path in sorted(by):
        its = by[path]
        best = sorted(its, key=lambda it: (it['corpus'] != 'crush', 'varied run' not in it['measure'], it['measure']))
        where = '; '.join('%s vs %s: %s%s' % (it['measure'], it['corpus'], it['value'],
                                              (' (lines %s <- `%s` %s)' % (it['lines'], it['source'], it['source_lines'])) if it['lines'] and it['source'] else
                                              ((' (<- `%s`)' % it['source']) if it['source'] else '')) for it in best[:3])
        if len(its) > 3:
            where += '; and in %d more of the lists' % (len(its) - 3)
        kinds = collections.Counter(it['sort'] for it in its if it['sort'])
        sort = ', '.join(k for k, _ in kinds.most_common(2)) or 'single lines'
        verdict = VERDICTS.get(path, 'idiom: ' + sort if sort != 'other' else 'idiom (read on both sides)')
        sorts[sort.split(',')[0]] += 1
        shown = sort.replace('other', 'code of no one kind')
        out.append('| `%s` | %s | %s | %s |' % (path, where, shown, verdict))
    with open(os.path.join(X.WORK, 'review.md'), 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('review: %d matches in %d files; by first sort: %s' % (len(items), len(by), dict(sorts.most_common())))
    other = [it for it in items.values() if it['sort'] == 'other' and it['path'] not in VERDICTS]
    print('matches sorted "other" with no verdict yet: %d' % len(other))
    for it in other:
        print('  %s | %s vs %s | %s | L%s <- %s L%s' % (it['path'], it['measure'], it['corpus'], it['value'], it['lines'], it['source'], it['source_lines']))


if __name__ == '__main__':
    main()
