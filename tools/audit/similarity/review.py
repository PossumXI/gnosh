#!/usr/bin/env python3
"""review.py - the list for the hand review, and its record.

It gathers, for the new code, the twenty highest files of each measure
against Crush (crush), Crush's whole history (hist) and Charm's libraries
(libs), and every file above the control set's highest, and says for each
match what the matched lines of the NEW file are made of. That sorting is
done on the new tree's own lines only, by simple rules:

  list or table      rows of literals: a list of strings, a table of test
                     cases, a map of names to true
  struct fields      a struct whose fields carry json tags, or an enum block
  locked accessor    a method that takes a lock, reads or sets a field, and
                     returns
  test scaffold      the head of a table-driven test or a fuzz test, its loop
                     and its first call
  short function     one-line getters and setters in a row
  error plumbing     calls followed by `if err != nil`
  other              none of the above: the ones to read first

The sorting is an aid, not the judgement. Every match in review.tsv was then
read on both sides (peek.py); VERDICTS below records the ones that are not
plain idiom, by file. Output: WORK/review.tsv, and WORK/review.md, which is
the per-file table README.md carries.
"""
import collections
