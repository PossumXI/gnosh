LIT = re.compile(r'^\s*(?:\{.*\},?|"[^"]*",?(?:\s*"[^"]*",?)*|`[^`]*`,?|[\w."\'-]+:\s*.*,|-?[\d.x]+,?)\s*(?://.*)?$')
TRUEMAP = re.compile(r'"\s*:\s*true')
FIELD = re.compile(r'^\s*\w+\s+[\w.\[\]*{}]+\s+`json:"|^\s*[A-Z]\w*\s*(?://.*)?$|^\s*\w+\s+\w+\s*=\s*(?:iota|"[^"]*"|\d+)')
LOCK = re.compile(r'\.(?:R?Lock|R?Unlock)\(\)')
TEST = re.compile(r'^\s*(?:func (?:Test|Fuzz|Benchmark)\w*\(|t\.Run\(|t\.Parallel\(\)|f\.Add\(|f\.Fuzz\(|for _, \w+ := range (?:tests|cases|tt|tc)|\w+ := \[\]struct|(?:tests|cases) := )')
ONELINE = re.compile(r'^\s*func \([^)]*\) \w+\([^)]*\)[^{]*\{ .* \}\s*$')
ERR = re.compile(r'if err != nil|return .*err\b')


def classify(lines):
    body = [l for l in lines if l.strip() and not l.strip().startswith('//') and l.strip() not in ('}', '{', ')', '(', '})', '},')]
    if not body:
        return 'other'
    n = len(body)

    def share(rx):
        return sum(1 for l in body if rx.search(l)) / n
    lit = share(LIT)
    if share(TRUEMAP) >= 0.3 or lit >= 0.6:
        return 'list or table'
    if share(TEST) >= 0.25 or (share(TEST) > 0 and lit >= 0.3):
        return 'test scaffold'
    if share(LOCK) >= 0.2:
        return 'locked accessor'
    if share(FIELD) >= 0.5:
        return 'struct fields'
    if share(ONELINE) >= 0.4:
        return 'short function'
    if share(ERR) >= 0.3:
        return 'error plumbing'
    return 'other'


